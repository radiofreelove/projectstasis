#!/usr/bin/env python3
"""
Check every color pair in data/palette.json against WCAG 2.2 contrast.

    python3 tools/check_contrast.py          Check and rewrite docs/contrast.md
    python3 tools/check_contrast.py --check  Check only; fail if docs/contrast.md is stale

Text pairs must reach 7:1 (WCAG 2.2 Level AAA, success criterion 1.4.6).
Non-text pairs (borders, focus outlines) must reach 3:1 (criterion 1.4.11).
Uses the WCAG relative luminance formula. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE = ROOT / "data" / "palette.json"
REPORT = ROOT / "docs" / "contrast.md"


def channel(value: int) -> float:
    c = value / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_color: str) -> float:
    hex_color = hex_color.lstrip("#")
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def ratio(fg: str, bg: str) -> float:
    a, b = luminance(fg), luminance(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def build_report(palette) -> tuple[str, list[str]]:
    colors = palette["colors"]
    limits = palette["thresholds"]
    failures = []
    lines = [
        "# Color contrast report",
        "",
        "Generated by `tools/check_contrast.py` from `data/palette.json`. Do not edit by hand.",
        "",
        f"Palette source: {palette['source']}.",
        "",
        f"Text must reach {limits['text']}:1 (WCAG 2.2 Level AAA). "
        f"Borders and focus outlines must reach {limits['non-text']}:1.",
        "",
        "| Theme | Where it is used | Foreground | Background | Ratio | Needs | Result |",
        "|---|---|---|---|---|---|---|",
    ]
    for pair in palette["pairs"]:
        fg_hex, bg_hex = colors[pair["fg"]], colors[pair["bg"]]
        value = ratio(fg_hex, bg_hex)
        need = limits[pair["type"]]
        ok = value >= need
        if not ok:
            failures.append(f"{pair['theme']}: {pair['use']} is {value:.2f}:1, needs {need}:1")
        lines.append(
            f"| {pair['theme']} | {pair['use']} | {pair['fg']} `{fg_hex}` | {pair['bg']} `{bg_hex}` | "
            f"{value:.2f}:1 | {need}:1 | {'Pass' if ok else 'FAIL'} |"
        )
    lines.append("")
    return "\n".join(lines), failures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    palette = json.loads(PALETTE.read_text(encoding="utf-8"))
    report, failures = build_report(palette)
    if args.check:
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != report:
            print("docs/contrast.md is out of date. Run python3 tools/check_contrast.py", file=sys.stderr)
            return 1
    else:
        REPORT.write_text(report, encoding="utf-8")
    if failures:
        print("Contrast failures:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1
    print(f"All {len(palette['pairs'])} color pairs pass.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
