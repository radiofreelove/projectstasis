#!/usr/bin/env python3
"""
Estimate the reading level of each page's main content.

    python3 tools/check_reading_level.py          Check and rewrite docs/reading-level.md
    python3 tools/check_reading_level.py --check  Check only; fail if the report is stale

Method: Flesch-Kincaid grade level on the text inside <main>, leaving out
the "Sources for this page" section (titles of official documents are not
ours to simplify). Each paragraph, list item, heading, table cell, label,
and definition counts as its own sentence, because that is how people read
a bulleted page. Syllables are counted with a simple vowel-group rule, so
treat the numbers as a guide, not a grade.

Target: grade 6 or lower. The check fails above MAX_GRADE.
Standard library only.
"""
from __future__ import annotations

import argparse
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
REPORT = ROOT / "docs" / "reading-level.md"
TARGET_GRADE = 6.0
MAX_GRADE = 8.0
SKIP_PAGES = {"sources.html", "404.html"}
BLOCKS = {"p", "li", "h1", "h2", "h3", "h4", "dt", "dd", "td", "th", "label", "legend", "caption", "summary", "button"}


class MainText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_main = 0
        self.skip_depth = 0
        self.depth = 0
        self.skip_at = []
        self.blocks = []
        self.current = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "main":
            self.in_main += 1
        self.depth += 1
        classes = (attrs.get("class") or "").split()
        if self.in_main and ("sources" in classes or "fewer-note" in classes or tag in {"script", "noscript"}):
            self.skip_at.append(self.depth)
        if tag in BLOCKS:
            self.flush()

    def handle_endtag(self, tag):
        if tag in BLOCKS:
            self.flush()
        if self.skip_at and self.skip_at[-1] == self.depth:
            self.skip_at.pop()
        self.depth -= 1
        if tag == "main":
            self.in_main -= 1

    def handle_data(self, data):
        if self.in_main and not self.skip_at:
            self.current.append(data)

    def flush(self):
        text = " ".join("".join(self.current).split())
        if text:
            self.blocks.append(text)
        self.current = []


WORD_RE = re.compile(r"[A-Za-z0-9$%'.\-]+")


def syllables(word: str) -> int:
    if any(ch.isdigit() for ch in word):
        return 2
    w = word.lower().strip(".'-")
    if not w:
        return 0
    if len(w) <= 3:
        return 1
    w = re.sub(r"(?:[^laeiouy]es|ed|[^laeiouy]e)$", "", w)
    w = re.sub(r"^y", "", w)
    groups = re.findall(r"[aeiouy]{1,2}", w)
    return max(1, len(groups))


def sentences_in(block: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", block)
    return [p for p in parts if WORD_RE.search(p)]


def score(blocks: list[str]):
    sentences = []
    for block in blocks:
        sentences.extend(sentences_in(block))
    words = [w for s in sentences for w in WORD_RE.findall(s) if any(c.isalnum() for c in w)]
    if not words or not sentences:
        return None
    syl = sum(syllables(w) for w in words)
    wps = len(words) / len(sentences)
    spw = syl / len(words)
    grade = 0.39 * wps + 11.8 * spw - 15.59
    return {"grade": grade, "words": len(words), "sentences": len(sentences), "wps": wps}


def build_report():
    rows = []
    failures = []
    for path in sorted(SITE.glob("*.html")):
        if path.name in SKIP_PAGES:
            continue
        parser = MainText()
        parser.feed(path.read_text(encoding="utf-8"))
        parser.flush()
        result = score(parser.blocks)
        if result is None:
            continue
        status = "On target" if result["grade"] <= TARGET_GRADE else ("Above target" if result["grade"] <= MAX_GRADE else "TOO HARD")
        if result["grade"] > MAX_GRADE:
            failures.append(f"{path.name}: grade {result['grade']:.1f}")
        rows.append((path.name, result, status))

    lines = [
        "# Reading level report",
        "",
        "Generated by `tools/check_reading_level.py`. Do not edit by hand.",
        "",
        f"Flesch-Kincaid grade level of each page's main text. Target: grade {TARGET_GRADE:.0f} or lower. "
        f"The check fails above grade {MAX_GRADE:.0f}. Source lists are left out. "
        "This is an estimate; plain words and short sentences matter more than the number.",
        "",
        "| Page | Grade | Words | Sentences | Words per sentence | Status |",
        "|---|---|---|---|---|---|",
    ]
    for name, r, status in rows:
        lines.append(f"| {name} | {r['grade']:.1f} | {r['words']} | {r['sentences']} | {r['wps']:.1f} | {status} |")
    lines.append("")
    return "\n".join(lines), failures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    report, failures = build_report()
    if args.check:
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != report:
            print("docs/reading-level.md is out of date. Run python3 tools/check_reading_level.py", file=sys.stderr)
            return 1
    else:
        REPORT.write_text(report, encoding="utf-8")
    print(report)
    if failures:
        print("Pages above the maximum grade:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
